package ovh.battistella.sillon.data.plex

import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable

/*
 * Wire models for the two Plex APIs Sillon talks to: plex.tv (account, PIN
 * sign-in, server discovery) and the Plex Media Server itself (library). Only
 * the fields Sillon reads are declared; everything else is ignored by the
 * lenient [PlexJson] decoder, so a Plex update adding fields can't break us.
 */

/** A sign-in PIN from `POST plex.tv/api/v2/pins`. [authToken] is set once the user approves it. */
@Serializable
data class PlexPin(
    val id: Long,
    val code: String,
    val authToken: String? = null,
    val expiresIn: Long = 0,
)

/** A device linked to the account, from `GET plex.tv/api/v2/resources`. */
@Serializable
data class PlexResource(
    val name: String,
    val clientIdentifier: String,
    val provides: String = "",
    val owned: Boolean = false,
    val accessToken: String? = null,
    val connections: List<PlexConnection> = emptyList(),
) {
    val isServer: Boolean get() = provides.split(',').any { it.trim() == "server" }
}

/** One way to reach a server: LAN address, public address or Plex relay. */
@Serializable
data class PlexConnection(
    val protocol: String = "",
    val address: String = "",
    val port: Int = 0,
    val uri: String,
    val local: Boolean = false,
    val relay: Boolean = false,
)

/** Every Plex Media Server response is wrapped as `{"MediaContainer": {...}}`. */
@Serializable
data class PlexResponse(
    @SerialName("MediaContainer") val container: MediaContainer = MediaContainer(),
)

@Serializable
data class MediaContainer(
    val size: Int = 0,
    val machineIdentifier: String? = null,
    @SerialName("Directory") val directories: List<PlexDirectory> = emptyList(),
    @SerialName("Metadata") val metadata: List<PlexMetadata> = emptyList(),
    @SerialName("Hub") val hubs: List<PlexHub> = emptyList(),
    /** Set on a play queue response (radios). */
    val playQueueID: Long? = null,
)

/** A group of search results of one [type] (`artist`, `album`, `track`…). */
@Serializable
data class PlexHub(
    val type: String = "",
    val title: String = "",
    val hubIdentifier: String = "",
    @SerialName("Metadata") val metadata: List<PlexMetadata> = emptyList(),
)

/** A library section. Music sections have `type == "artist"`. */
@Serializable
data class PlexDirectory(
    val key: String,
    val title: String,
    val type: String = "",
) {
    val isMusic: Boolean get() = type == TYPE_MUSIC_SECTION

    companion object {
        const val TYPE_MUSIC_SECTION = "artist"
    }
}

/**
 * An artist, album or track. Plex uses the same shape for all three, with the
 * hierarchy flattened into `parent*` (one level up) and `grandparent*` (two
 * levels up): for a track, the parent is the album and the grandparent the artist.
 */
@Serializable
data class PlexMetadata(
    /** Empty for stations, which only have a [key]. */
    val ratingKey: String = "",
    /** Server path of the item; for a station, the path to play it from. */
    val key: String? = null,
    val type: String = "",
    val title: String = "",
    val parentRatingKey: String? = null,
    val parentTitle: String? = null,
    val grandparentTitle: String? = null,
    /** For a track: its artist. */
    val grandparentRatingKey: String? = null,
    /** Track artist when it differs from the album artist (compilations, featurings). */
    val originalTitle: String? = null,
    val index: Int? = null,
    /** For a track: the disc number. */
    val parentIndex: Int? = null,
    val year: Int? = null,
    val duration: Long? = null,
    val leafCount: Int? = null,
    /** The user's rating out of 10 (5 stars = 10), when rated. */
    val userRating: Float? = null,
    /** Number of listeners on Last.fm, which Plex uses as the track's popularity. */
    val ratingCount: Long? = null,
    /** How many times the user played it. */
    val viewCount: Int? = null,
    /** An artist's radio, with `includeStations=1`. */
    @SerialName("Stations") val stations: PlexStations? = null,
    /** Track gain in dB from servers that give it directly (Jellyfin's NormalizationGain). */
    val normalizationGain: Float? = null,
    val thumb: String? = null,
    val parentThumb: String? = null,
    val grandparentThumb: String? = null,
    /** Mosaic of a playlist's covers, generated by the server. */
    val composite: String? = null,
    @SerialName("Media") val media: List<PlexMedia> = emptyList(),
) {
    /** Cover art: a track usually has none of its own and borrows its album's. */
    val artwork: String? get() = thumb ?: composite ?: parentThumb ?: grandparentThumb

    /** Server path of the first playable file, e.g. `/library/parts/12/1700000000/file.flac`. */
    val partKey: String? get() = media.firstOrNull()?.parts?.firstOrNull()?.key

    /** The user's rating in stars (0–5), when rated. */
    val stars: Float? get() = userRating?.takeIf { it > 0f }?.div(2f)

    /** Loudness gains of the track's audio stream, when Plex analysed it. */
    private val audioStream: PlexStream?
        get() = media.firstOrNull()?.parts?.firstOrNull()?.streams?.firstOrNull { it.streamType == 2 }

    /** dB to apply for the same loudness track to track; set directly for Jellyfin. */
    val trackGain: Float? get() = normalizationGain ?: audioStream?.gain

    /** dB to apply for the same loudness album to album, keeping the album's own dynamics. */
    val albumGain: Float? get() = audioStream?.albumGain ?: trackGain

    /** The artist to show for a track. */
    val trackArtist: String? get() = originalTitle ?: grandparentTitle
}

@Serializable
data class PlexMedia(
    val audioCodec: String? = null,
    val container: String? = null,
    @SerialName("Part") val parts: List<PlexPart> = emptyList(),
)

@Serializable
data class PlexPart(
    val key: String,
    val duration: Long? = null,
    /** Only in full item responses (not listings): see [PlexApi.metadataBatch]. */
    @SerialName("Stream") val streams: List<PlexStream> = emptyList(),
)

/**
 * A stream of a file. For audio (streamType 2), Plex adds ReplayGain-style
 * values once the library's loudness analysis has run: gains in dB to bring
 * the track (or its album) to a common loudness.
 */
@Serializable
data class PlexStream(
    val streamType: Int = 0,
    val gain: Float? = null,
    val albumGain: Float? = null,
    val peak: Float? = null,
    val albumPeak: Float? = null,
)

@Serializable
data class PlexStations(
    @SerialName("Metadata") val metadata: List<PlexMetadata> = emptyList(),
)
